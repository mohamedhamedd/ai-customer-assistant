import { z } from "zod";
import type { SupabaseClient } from "@supabase/supabase-js";
import { db } from "@/lib/db/supabase";
import type { Database } from "@/lib/db/database.types";
import type { Channel } from "@/lib/db/enums";
import { retrieve, type Source } from "@/lib/rag/retrieve";
import { formatHuman, formatLocal, zonedLocalToUtc } from "./time";

// The agent's three tools (design D-02, D-08). One registry serves text chat
// and voice: same schemas, same validation, same database functions.
//
// Rule R1 (design §8): a tool result goes straight into the model's context
// and the model can repeat anything in it, so results contain only ids,
// statuses and values THIS visitor supplied, never stored lead data.

export interface ToolContext {
  businessId: string;
  conversationId: string;
  channel: Channel;
  timeZone: string;
  now: () => Date;
  // Defaults to the service-role client; tests pass a stub.
  client?: SupabaseClient<Database>;
}

// What the model sees. Always an object with ok.
export type ToolOutput =
  | ({ ok: true } & Record<string, unknown>)
  | { ok: false; error: string; message: string };

export interface ToolRunResult {
  output: ToolOutput;
  // Citations for the UI (search_knowledge only); never generated by the model.
  sources?: Source[];
}

// Neutral definition; the chat and realtime adapters wrap it in their own
// envelope (Chat Completions nests it under `function`, Realtime doesn't).
export interface ToolDefinition {
  name: string;
  description: string;
  parameters: Record<string, unknown>;
}

export interface Tool extends ToolDefinition {
  // Writes data. A write that times out may still commit, so its outcome is
  // reported as unknown rather than failed (execute.ts).
  writes: boolean;
  schema: z.ZodType;
  run(args: unknown, ctx: ToolContext): Promise<ToolRunResult>;
}

function defineTool<S extends z.ZodType>(spec: ToolDefinition & { writes: boolean; schema: S; run(args: z.output<S>, ctx: ToolContext): Promise<ToolRunResult> }): Tool {
  return spec as unknown as Tool;
}

export const invalid = (message: string): ToolRunResult => ({ output: { ok: false, error: "invalid_input", message } });

// ---------------------------------------------------------------------------
// Field rules
// ---------------------------------------------------------------------------

// Models sometimes send "" or null for an optional field they don't have.
const blankToUndefined = (v: unknown) => (v === null || (typeof v === "string" && v.trim() === "") ? undefined : v);

const optional = <T extends z.ZodType>(schema: T) => z.preprocess(blankToUndefined, schema.optional());

const nameField = z
  .string({ error: "name is required" })
  .transform((s) => s.trim().replace(/\s+/g, " "))
  .pipe(z.string().min(1, "name is required").max(100, "name is too long"));

const emailField = z
  .string()
  .transform((s) => s.trim().toLowerCase())
  .pipe(z.email("this email address doesn't look valid; ask the customer to check it"));

// Stored as "+" and digits only (design §3.7). 7 to 15 digits covers local
// and international (E.164) numbers.
export const normalisePhone = (s: string) => s.trim().replace(/[\s().-]/g, "");
const phoneField = z
  .string()
  .transform(normalisePhone)
  .pipe(z.string().regex(/^\+?\d{7,15}$/, "this phone number doesn't look valid; ask the customer to check it"));

