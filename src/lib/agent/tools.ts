// Models sometimes send "" or null for an optional field they don't have.
const blankToUndefined = (v: unknown) => (v === null || (typeof v === "string" && v.trim() === "") ? undefined : v);

const optional = <T extends z.ZodType>(schema: T) => z.preprocess(blankToUndefined, schema.optional());

const nameField = z
  .string({ error: "name is required" })
  .transform((s) => s.trim().replace(/\s+/g, " "))
  .pipe(z.string().min(1, "name is required").max(100, "name is too long"));

const emailField = z
  .string()
  .transform((s) => s.trim().toLowerCase())
  .pipe(z.email("this email address doesn't look valid; ask the customer to check it"));

// Stored as "+" and digits only (design §3.7). 7 to 15 digits covers local
// and international (E.164) numbers.
export const normalisePhone = (s: string) => s.trim().replace(/[\s().-]/g, "");
const phoneField = z
  .string()
  .transform(normalisePhone)
  .pipe(z.string().regex(/^\+?\d{7,15}$/, "this phone number doesn't look valid; ask the customer to check it"));

