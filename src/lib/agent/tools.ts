// save_lead
// ---------------------------------------------------------------------------

export const saveLeadSchema = z
  .object({
    name: nameField,
    email: optional(emailField),
    phone: optional(phoneField),
    interest: optional(z.string().trim().max(200, "interest is too long")),
  })
  .superRefine((v, ctx) => {
    if (!v.email && !v.phone) ctx.addIssue({ code: "custom", message: "an email or a phone number is required", path: ["email"] });
  });

const saveLead = defineTool({
  name: "save_lead",
  writes: true,
  description:
    "Save the customer's contact details so the team can follow up. Requires a name and at least one of email or phone. Read the details back to the customer and get confirmation before calling.",
  parameters: {
    type: "object",
    properties: {
      name: { type: "string", description: "The customer's name." },
      email: { type: "string", description: "Email address, if given." },
      phone: { type: "string", description: "Phone number, if given." },
      interest: { type: "string", description: "What they are interested in, e.g. 'Invisalign'. Optional." },
    },
    required: ["name"],
    additionalProperties: false,
  },
  schema: saveLeadSchema,
  async run(args, ctx) {
    const { error } = await (ctx.client ?? db()).rpc("save_lead", {
      p_business_id: ctx.businessId,
      p_conversation_id: ctx.conversationId,
      p_channel: ctx.channel,
      p_name: args.name,
      p_email: args.email,
      p_phone: args.phone,
      p_interest: args.interest,
    });
    if (error) throw new Error(`save_lead failed: ${error.message}`);
    // R1: echo what the customer gave; nothing read back from the leads table.
    return { output: { ok: true, saved: true, details: { name: args.name, email: args.email, phone: args.phone, interest: args.interest } } };
  },
});

