// The agent's three tools (design D-02, D-08). One registry serves text chat
// and voice: same schemas, same validation, same database functions.
//
// Rule R1 (design §8): a tool result goes straight into the model's context
// and the model can repeat anything in it, so results contain only ids,
// statuses and values THIS visitor supplied, never stored lead data.

export interface ToolContext {
  businessId: string;
  conversationId: string;
  channel: Channel;
  timeZone: string;
  now: () => Date;
  // Voice only, for the audit trail: the call this ran in and the model's id
  // for the tool call, so an answer's cards come from exactly its tool calls.
  voiceCallId?: string;
  realtimeCallId?: string;
  // Defaults to the service-role client; tests pass a stub.
  client?: SupabaseClient<Database>;
  // What a consultation's service is checked against (service-choice.ts).
  // Defaults to the database; tests pass their own.
  serviceEvidence?: (ctx: ToolContext) => Promise<ServiceEvidence>;
  // The business's opening hours (Admin > Opening hours), that a requested
  // time is checked against. Defaults to the database; tests pass their own.
  openingHours?: (ctx: ToolContext) => Promise<Week>;
  // The requests made in this conversation, that change_consultation_request
  // finds one in. Defaults to the database; tests pass their own.
  conversationRequests?: (ctx: ToolContext) => Promise<StoredRequest[]>;
}

// What the model sees. Always an object with ok.
export type ToolOutput =
  | ({ ok: true } & Record<string, unknown>)
  // details: confirm_first only, what would be saved (confirm.ts).
  // options: choose_service and service_not_found, service names to offer.
  // hours, closed_dates, notes: outside_opening_hours, the week's hours (one
  // line a day), the coming closed dates, and the business's notes.
  | { ok: false; error: string; message: string; details?: Record<string, unknown>; options?: string[]; hours?: string[]; closed_dates?: string[]; notes?: string };

export interface ToolRunResult {
  output: ToolOutput;
  // Citations for the UI (search_knowledge only); never generated by the model.
  sources?: Source[];
}

// Neutral definition; the chat and realtime adapters wrap it in their own
// envelope (Chat Completions nests it under `function`, Realtime doesn't).
export interface ToolDefinition {
  name: string;
  description: string;
  parameters: Record<string, unknown>;
}

// Confirm before write (confirm.ts): a write tool's first call with new
// details only proposes them; the same details commit once the customer has
// answered.
export interface ConfirmSpec<A> {
  // key: what identifies the write (the contact, or the time slot); the
  // proposal and the commit must match on it. details: what would be saved,
  // for the model to read back. Null when run() will reject the arguments
  // anyway (nothing is written, and the model hears the real problem first).
  propose(args: A, ctx: ToolContext): { key: string; details: Record<string, unknown> } | null;
}

// Before anything else: settles the arguments (the consultation's service, by
// its exact name), or answers instead of running.
export type Prepared<A> = { args: A } | { result: ToolRunResult };

export interface Tool extends ToolDefinition {
  // Writes data. A write that times out may still commit, so its outcome is
  // reported as unknown rather than failed (execute.ts).
  writes: boolean;
  schema: z.ZodType;
  confirm?: ConfirmSpec<unknown>;
  prepare?(args: unknown, ctx: ToolContext): Promise<Prepared<unknown>>;
  run(args: unknown, ctx: ToolContext): Promise<ToolRunResult>;
}

function defineTool<S extends z.ZodType>(
  spec: ToolDefinition & {
    writes: boolean;
    schema: S;
    confirm?: ConfirmSpec<z.output<S>>;
    prepare?(args: z.output<S>, ctx: ToolContext): Promise<Prepared<z.output<S>>>;
    run(args: z.output<S>, ctx: ToolContext): Promise<ToolRunResult>;
  },
): Tool {
  return spec as unknown as Tool;
}

export const invalid = (message: string): ToolRunResult => ({ output: { ok: false, error: "invalid_input", message } });

