const MAX_DAYS_AHEAD = 183;

export const consultationSchema = z.object({
  service: z.string().trim().min(2, "service is required").max(120, "service is too long"),
  preferred_datetime: z.string().trim(),
  notes: optional(z.string().trim().max(500, "notes are too long")),
});

export type PreferredTime = { ok: true; at: Date } | { ok: false; message: string };

// Pure, so the date rules are unit-tested without a database.
export function resolvePreferredTime(local: string, timeZone: string, now: Date): PreferredTime {
  const parsed = zonedLocalToUtc(local, timeZone);
  if (!parsed.ok) {
    return {
      ok: false,
      message:
        parsed.reason === "format"
          ? "preferred_datetime must be local time in the format YYYY-MM-DDTHH:mm, e.g. 2026-10-20T15:00"
          : `${local} does not exist in ${timeZone} (invalid date, or skipped by a clock change); ask the customer for another time`,
    };
  }
  if (parsed.at.getTime() <= now.getTime()) {
    return { ok: false, message: `that time is in the past (it is now ${formatHuman(now, timeZone)}); ask the customer for a future date` };
  }
  if (parsed.at.getTime() - now.getTime() > MAX_DAYS_AHEAD * 86_400_000) {
    return { ok: false, message: "that date is more than 6 months away; ask the customer for a nearer date" };
  }
  return { ok: true, at: parsed.at };
}

// The business's services, what the customer said, and the options the agent
// last offered if the customer has answered since.
const SAID = 30;

async function serviceEvidenceFromDb(ctx: ToolContext): Promise<ServiceEvidence> {
  const client = ctx.client ?? db();
  const [services, said, offer] = await Promise.all([
    client.from("services").select("name, requestable").eq("business_id", ctx.businessId).order("position"),
    client.from("messages").select("content").eq("conversation_id", ctx.conversationId).eq("role", "user").order("id", { ascending: false }).limit(SAID),
    client
      .from("tool_calls")
      .select("result, created_at")
      .eq("conversation_id", ctx.conversationId)
      .eq("name", "create_consultation_request")
      .eq("result->>error", "choose_service")
      .order("id", { ascending: false })
      .limit(1)
      .maybeSingle(),
  ]);
  for (const r of [services, said, offer]) if (r.error) throw new Error(`Loading the services failed: ${r.error.message}`);

  let offered: string[] = [];
  if (offer.data) {
    // Answered: a customer message after the offer (a voice item still being
    // transcribed counts: the customer has spoken).
    const { data: answer, error } = await client
      .from("messages")
      .select("id")
      .eq("conversation_id", ctx.conversationId)
      .eq("role", "user")
      .gt("created_at", offer.data.created_at)
      .limit(1)
      .maybeSingle();
    if (error) throw new Error(`Loading the services failed: ${error.message}`);
    const options = (offer.data.result as { options?: unknown }).options;
    if (answer && Array.isArray(options)) offered = options.filter((o): o is string => typeof o === "string");
  }
  return {
    services: services.data ?? [],
    customerSaid: (said.data ?? []).flatMap((m) => (m.content ? [m.content] : [])).reverse(),
    offered,
  };
}

async function openingHoursFromDb(ctx: ToolContext): Promise<Week> {
  const client = ctx.client ?? db();
  const [hours, business, closed] = await Promise.all([
    client.from("opening_hours").select("day, opens, closes, weeks").eq("business_id", ctx.businessId).order("day").order("opens"),
    client.from("businesses").select("last_start_before_close, hours_notes").eq("id", ctx.businessId).single(),
    client.from("closed_dates").select("date, label").eq("business_id", ctx.businessId).order("date"),
  ]);
  if (hours.error || business.error || closed.error) throw new Error(`Loading the opening hours failed: ${(hours.error ?? business.error ?? closed.error)!.message}`);
  return {
    // Postgres returns "09:00:00".
    hours: hours.data.map((r) => ({ day: r.day, opens: r.opens.slice(0, 5), closes: r.closes.slice(0, 5), weeks: r.weeks })),
    lastStartBeforeClose: business.data.last_start_before_close,
    notes: business.data.hours_notes,
    closed: closed.data,
  };
}

const createConsultationRequest = defineTool({
  name: "create_consultation_request",
  writes: true,
  description:
    "Create a consultation REQUEST for the team to confirm (not a booking). The customer's contact details must already be saved with save_lead. The first call for a time saves nothing: it returns the details to read back to the customer. Call again with the same details after they confirm.",
  parameters: {
    type: "object",
    properties: {
      service: {
        type: "string",
        description: "The service the consultation is for: its exact name if you know it, otherwise the customer's words. The tool checks it against the business's services.",
      },
      preferred_datetime: {
        type: "string",
        description: "Preferred date and time as LOCAL time in the business's timezone, format YYYY-MM-DDTHH:mm, e.g. 2026-10-20T15:00.",
      },
      notes: { type: "string", description: "Anything else the customer wants the team to know. Optional." },
    },
    required: ["service", "preferred_datetime"],
    additionalProperties: false,
  },
  schema: consultationSchema,
  // The service, from the business's services table (service-choice.ts);
  // then the time, against its opening hours. Neither table: as before.
  async prepare(args, ctx) {
    const [evidence, week] = await Promise.all([(ctx.serviceEvidence ?? serviceEvidenceFromDb)(ctx), (ctx.openingHours ?? openingHoursFromDb)(ctx)]);
    const choice = chooseService(args.service, evidence);
    if (choice.kind === "ok") {
      // An invalid or past time is left to run(), which says what's wrong.
      const when = resolvePreferredTime(args.preferred_datetime, ctx.timeZone, ctx.now());
      const start = when.ok ? startCheck(week, args.preferred_datetime) : null;
      if (when.ok && start && !start.ok) {
        const at = formatHuman(when.at, ctx.timeZone);
        const why =
          start.reason === "closed"
            ? `the business is closed at that time (${at})`
            : start.reason === "closed_date"
              ? `the business is closed on that date${start.label ? ` (${start.label})` : ""}, ${at}`
              : `${at} is too close to closing: the last appointment then starts at ${formatTime(start.latest)}`;
        const closed = upcomingClosed(week.closed, formatLocal(ctx.now(), ctx.timeZone).slice(0, 10), 10).map(formatClosedDate);
        return {
          result: {
            output: {
              ok: false,
              error: "outside_opening_hours",
              message: `Nothing is saved: ${why}. Tell the customer, and suggest a time within the opening hours (hours, local time)${start.reason === "too_late" ? `, such as ${formatTime(start.latest)} or earlier` : ""}${week.notes ? ", keeping to the notes" : ""}; ask which they prefer.`,
              ...(week.hours.length ? { hours: describeHours(week.hours) } : {}),
              ...(closed.length ? { closed_dates: closed } : {}),
              ...(week.notes ? { notes: week.notes } : {}),
            },
          },
        };
      }
      return { args: { ...args, service: choice.service } };
    }
    if (choice.kind === "choose") {
      return {
        result: {
          output: {
            ok: false,
            error: "choose_service",
            message:
              "Nothing is saved: the customer must choose the service. Ask them which of these options they want (or, for one option, whether it is what they mean), naming each exactly as written, and wait for their answer. Don't choose for them. Then call this tool again with the option they chose.",
            options: choice.options,
          },
        },
      };
    }
    const offer = choice.options.length
      ? `Tell the customer, and offer the services they can request${choice.options.length === MAX_LISTED ? " (some of them)" : ""}: the options.`
      : "This business takes no consultation requests here: offer to have the team contact the customer instead.";
    return {
      result: {
        output: {
          ok: false,
          error: "service_not_found",
          message: `Nothing is saved. "${args.service}" ${choice.listed ? "can't be requested as a consultation" : "isn't one of the services customers can request"}. ${offer}`,
          options: choice.options,
        },
      },
    };
  },
  confirm: {
    // The time slot and the service. The service by its words, so wording
    // may differ ("teeth whitening", "teeth whitening consultation"); with a
    // services table it is the exact name, so another service is a new
    // proposal, read back before it's saved.
    propose: (args, ctx) => {
      const when = resolvePreferredTime(args.preferred_datetime, ctx.timeZone, ctx.now());
      if (!when.ok) return null;
      return {
        key: JSON.stringify([when.at.toISOString(), words(args.service).sort()]),
        details: { service: args.service, preferred_time: formatHuman(when.at, ctx.timeZone), notes: args.notes },
      };
    },
  },
  async run(args, ctx) {
    const when = resolvePreferredTime(args.preferred_datetime, ctx.timeZone, ctx.now());
    if (!when.ok) return invalid(when.message);

    const { data, error } = await (ctx.client ?? db()).rpc("create_consultation_request", {
      p_business_id: ctx.businessId,
      p_conversation_id: ctx.conversationId,
      p_service: args.service,
      p_preferred_at: when.at.toISOString(),
      p_notes: args.notes,
    });
    if (error?.message === "lead_required") {
      return {
        output: {
          ok: false,
          error: "lead_required",
          message: "The customer's contact details aren't saved yet. Get their name and email or phone, confirm them, call save_lead, then try again.",
        },
      };
    }
    if (error) throw new Error(`create_consultation_request failed: ${error.message}`);

    const row = data as { request_id: string; status: string; service: string; created: boolean };
    return {
      output: {
        ok: true,
        request_id: row.request_id,
        status: row.status,
        already_requested: !row.created,
        // On a repeat, the service as first requested (the wording may differ).
        service: row.service ?? args.service,
        // The action card shows this string as is.
        preferred_time: formatHuman(when.at, ctx.timeZone),
        preferred_datetime: formatLocal(when.at, ctx.timeZone),
        note: "This is a request. The team will contact the customer to confirm.",
      },
    };
  },
});

export const TOOLS: Record<string, Tool> = Object.fromEntries(
  [searchKnowledge, saveLead, createConsultationRequest].map((t) => [t.name, t]),
);

export function toolDefinitions(tools: Record<string, Tool> = TOOLS): ToolDefinition[] {
  return Object.values(tools).map(({ name, description, parameters }) => ({ name, description, parameters }));
}
